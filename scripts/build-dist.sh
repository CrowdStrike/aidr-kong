local AzureAI = (function()
  return {
    ["/chat/completions"] = {
      request  = OpenAI["/v1/chat/completions"].request,
      response = OpenAI["/v1/chat/completions"].response,
    },
  }
end)()

-- ---------------------------------------------------------------------------
-- translator: kong (sniffs response format, delegates to other translators)
-- ---------------------------------------------------------------------------
local KongAI = (function()
  local function detect_and_parse_response(response)
    if type(response) ~= "table" then return nil, "Invalid response object" end
    if response.object == "chat.completion" then
      return OpenAI["/v1/chat/completions"].response(response)
    end
    if response.object == "text_completion" then
      return OpenAI["/v1/completions"].response(response)
    end
    if response.type == "message" then
      return Anthropic["/v1/messages"].response(response)
    end
    if type(response.output) == "table" and type(response.output.message) == "table" then
      return Bedrock["converse"].response(response)
    end
    return nil, "Unrecognized response format from Kong AI Proxy"
  end

  return {
    ["/llm/v1/chat"] = {
      request  = OpenAI["/v1/chat/completions"].request,
      response = detect_and_parse_response,
    },
    ["/llm/v1/completions"] = {
      request  = OpenAI["/v1/completions"].request,
      response = OpenAI["/v1/completions"].response,
    },
  }
end)()

-- ---------------------------------------------------------------------------
-- Static translator registry (replaces dynamic pcall(require, ...) lookup)
-- ---------------------------------------------------------------------------
local TRANSLATORS = {
  openai    = OpenAI,
  anthropic = Anthropic,
  bedrock   = Bedrock,
  cohere    = Cohere,
  gemini    = Gemini,
  azureai   = AzureAI,
  kong      = KongAI,
}

local function get_translator(provider)
  local t = TRANSLATORS[provider]
  if not t then return nil, "Unknown translator '" .. provider .. "'" end
  return t
end

local function rewrite_llm_message(original, message_mapping, new_messages)
  local updated = false
  if not new_messages then return original, updated end
  for idx, prompt_message in ipairs(new_messages) do
    local this_message_lookup = message_mapping.lookup[idx]
    if this_message_lookup ~= nil then
      local content  = original
      local last_part = table.remove(this_message_lookup)
      for _, part in ipairs(this_message_lookup) do
        content = content[part]
      end
      if content[last_part] ~= prompt_message.content then
        content[last_part] = prompt_message.content
        updated = true
      end
    end
  end
  return original, updated
end

