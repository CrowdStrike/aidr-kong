#!/usr/bin/env bash
# build-dist.sh — Generate streamable single-file dist artifacts for Konnect upload.
#
# Output: dist/<plugin>/handler.lua and dist/<plugin>/schema.lua for all three plugins.
# Requirements: untrusted_lua = lax on the Kong data plane.
#
# Usage: bash scripts/build-dist.sh [--repo-root <path>]
#   Defaults to the directory containing this script's parent.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="${REPO_ROOT:-$(cd "$SCRIPT_DIR/.." && pwd)}"

SRC="$REPO_ROOT/kong/plugins"
DIST="$REPO_ROOT/dist"

info() { echo "[build-dist] $*"; }

# ---------------------------------------------------------------------------
# Schema copy (source schemas are already sandbox-safe after in-source fixes)
# ---------------------------------------------------------------------------

copy_schema() {
  local plugin="$1"
  local dest="$DIST/$plugin"
  mkdir -p "$dest"
  cp "$SRC/$plugin/schema.lua" "$dest/schema.lua"
  info "schema: $plugin → dist/$plugin/schema.lua"
}

# ---------------------------------------------------------------------------
# Generate inlined handler for crowdstrike-aidr-request and -response
#
# The shared library is inlined in dependency order using IIFEs so each
# module's internal locals stay scoped.  Dynamic require() calls are replaced
# with static table lookups, and setmetatable is eliminated.
# ---------------------------------------------------------------------------

generate_shared_handler() {
  local plugin="$1"     # e.g. crowdstrike-aidr-request
  local priority="$2"   # e.g. 780
  local version="$3"    # e.g. 0.7.0
  local handler_class="$4"  # e.g. CrowdStrikeAIDRRequestHandler
  local dest="$DIST/$plugin"
  mkdir -p "$dest"

  info "handler: $plugin → dist/$plugin/handler.lua"
  cat > "$dest/handler.lua" << 'HANDLER_EOF'
-- dist handler — generated by scripts/build-dist.sh, do not edit.
-- Requires: untrusted_lua = lax (Kong Gateway 3.14+ / AI Gateway 2.x)
local cjson = require("cjson.safe")
local http  = require("resty.http")
local gzip  = require("kong.tools.gzip")

-- ---------------------------------------------------------------------------
-- model (no setmetatable)
-- ---------------------------------------------------------------------------
local AidrRoles = {
  PromptRoleSystem = "system",
  PromptRoleUser   = "user",
  PromptRoleLlm    = "assistant",
}

local function add_message(self, content, role, path, pos)
  if pos ~= nil then
    table.insert(self.messages, pos, { content = content, role = role })
    table.insert(self.lookup,   pos, path)
  else
    table.insert(self.messages, { content = content, role = role })
    table.insert(self.lookup,   path)
  end
end

local function NewJSONMessageMap()
  return { messages = {}, lookup = {}, tools = nil, add_message = add_message }
end

-- ---------------------------------------------------------------------------
-- translator: openai
-- ---------------------------------------------------------------------------
local OpenAI = (function()
  local role_transform = {
    ["developer"] = AidrRoles.PromptRoleSystem,
    ["system"]    = AidrRoles.PromptRoleSystem,
    ["user"]      = AidrRoles.PromptRoleUser,
    ["assistant"] = AidrRoles.PromptRoleLlm,
  }

  local function prepare_chat_completions_request(request)
    if type(request) ~= "table" then return nil, "Invalid llm request" end
    local ret = NewJSONMessageMap()
    for idx, message in ipairs(request.messages) do
      local role    = role_transform[message.role] or message.role
      local content = message.content
      if type(content) == "string" then
        ret:add_message(content, role, { "messages", idx, "content" })
      elseif type(content) == "table" then
        for jdx, part in ipairs(content) do
          if part.type == "text" then
            ret:add_message(part.text, role, { "messages", idx, "content", jdx, "text" })
          end
        end
      elseif content == nil and type(message.tool_calls) == "table" then
        ret:add_message(nil, "assistant", nil)
      end
    end
    if type(request.tools) == "table" and #request.tools > 0 then
      ret.tools = request.tools
    end
    return ret
  end

  local function prepare_chat_completions_response(response)
    if type(response) ~= "table" then return nil, "Invalid response object" end
    if response.object ~= "chat.completion" then return nil, "Invalid response object" end
    local ret = NewJSONMessageMap()
    for idx, choice in ipairs(response.choices) do
      local role    = role_transform[choice.message.role] or choice.message.role
      local content = choice.message.content
      if content then
        ret:add_message(content, role, { "choices", idx, "message", "content" })
      end
    end
    return ret
  end

  local function prepare_completions_request(request)
    if type(request) ~= "table" then return nil, "Invalid llm request" end
    local ret    = NewJSONMessageMap()
    local prompt = request.prompt
    if type(prompt) == "string" then
      ret:add_message(prompt, "user", { "prompt" })
    elseif type(prompt) == "table" then
      for idx, message in ipairs(prompt) do
        ret:add_message(message, "user", { "prompt", idx })
      end
    end
    return ret
  end

  local function prepare_completions_response(response)
    if type(response) ~= "table" then return nil, "Invalid response object" end
    if response.object ~= "text_completion" then return nil, "Invalid response object" end
    local ret = NewJSONMessageMap()
    for idx, choice in ipairs(response.choices) do
      if choice.text then
        ret:add_message(choice.text, "assistant", { "choices", idx, "text" })
      end
    end
    return ret
  end

  return {
    ["/v1/chat/completions"] = {
      request  = prepare_chat_completions_request,
      response = prepare_chat_completions_response,
    },
    ["/v1/completions"] = {
      request  = prepare_completions_request,
      response = prepare_completions_response,
    },
  }
end)()

-- ---------------------------------------------------------------------------
-- translator: anthropic
-- ---------------------------------------------------------------------------
local Anthropic = (function()
  local function convert_tools(anthropic_tools)
    local tools = {}
    for _, tool in ipairs(anthropic_tools) do
      if type(tool) == "table" and type(tool.name) == "string" then
        table.insert(tools, {
          type = "function",
          ["function"] = {
            name        = tool.name,
            description = tool.description,
            parameters  = tool.input_schema,
          },
        })
      end
    end
    return tools
  end

  local function add_content_part(ret, part, role, idx, jdx)
    if part.type == "text" and type(part.text) == "string" then
      ret:add_message(part.text, role, { "messages", idx, "content", jdx, "text" })
    elseif part.type == "tool_result" then
      local tool_content = part.content
      if type(tool_content) == "string" then
        ret:add_message(tool_content, role, { "messages", idx, "content", jdx, "content" })
      elseif type(tool_content) == "table" then
        for kdx, block in ipairs(tool_content) do
          if block.type == "text" and type(block.text) == "string" then
            ret:add_message(block.text, role, { "messages", idx, "content", jdx, "content", kdx, "text" })
          end
        end
      end
    end
  end

  local function prepare_messages_request(request)
    if type(request) ~= "table" then return nil, "Invalid llm request" end
    local ret = NewJSONMessageMap()
    for idx, message in ipairs(request.messages or {}) do
      local role    = message.role
      local content = message.content
      if type(content) == "string" then
        ret:add_message(content, role, { "messages", idx, "content" })
      elseif type(content) == "table" then
        for jdx, part in ipairs(content) do
          add_content_part(ret, part, role, idx, jdx)
        end
      end
    end
    return ret
  end

  local function prepare_messages_response(response)
    if type(response) ~= "table" then return nil, "Invalid response object" end
    if response.type ~= "message" then return nil, "Invalid response object" end
    local content = response.content
    if type(content) ~= "table" then return nil, "Invalid response object" end
    local role = response.role or "assistant"
    local ret  = NewJSONMessageMap()
    for idx, part in ipairs(content) do
      if type(part) == "table" and part.type == "text" and type(part.text) == "string" then
        ret:add_message(part.text, role, { "content", idx, "text" })
      end
    end
    return ret
  end

  return {
    ["/v1/messages"] = {
      request = function(request)
        local ret, err = prepare_messages_request(request)
        if err ~= nil or ret == nil then return ret, err end
        local system = request.system
        if system ~= nil then
          if type(system) == "string" then
            ret:add_message(system, "system", { "system" })
          elseif type(system) == "table" then
            for idx, content in ipairs(system) do
              if content.type == "text" then
                ret:add_message(content.text, "system", { "system", idx, "text" }, 1)
              end
            end
          end
        end
        if type(request.tools) == "table" and #request.tools > 0 then
          ret.tools = convert_tools(request.tools)
        end
        return ret
      end,
      response = prepare_messages_response,
    },
  }
end)()

