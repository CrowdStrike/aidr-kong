local internalError = { status = "Internal server error" }

local function resolve_user_id(config)
  local consumer = kong.client.get_consumer()
  if consumer then
    if consumer.username  then return consumer.username  end
    if consumer.custom_id then return consumer.custom_id end
  end
  local credential = kong.client.get_credential()
  if credential then return credential.id end
  return config.user_id
end

local function get_aidr_fields(config, mode)
  local body = {}
  body.source_ip  = kong.client.get_forwarded_ip()
  body.event_type = mode == "request" and "input" or "output"

  if config.app_id and config.app_id ~= ngx.null then
    body.app_id = config.app_id
  end

  local user_id = resolve_user_id(config)
  if user_id and user_id ~= ngx.null then
    body.user_id = user_id
  end

  if config.llm_provider and config.llm_provider ~= ngx.null then
    body.llm_provider = config.llm_provider
  elseif config.upstream_llm and config.upstream_llm.provider then
    local provider_map = {
      openai    = "OpenAI",
      anthropic = "Anthropic",
      azureai   = "Azure OpenAI",
      bedrock   = "AWS Bedrock",
      cohere    = "Cohere",
      gemini    = "Google Gemini",
      kong      = "Kong AI Gateway",
    }
    body.llm_provider = provider_map[config.upstream_llm.provider] or config.upstream_llm.provider
  end

  if config.model and config.model ~= ngx.null then
    body.model = config.model
  end
  if config.model_version and config.model_version ~= ngx.null then
    body.model_version = config.model_version
  end
  if config.source_location and config.source_location ~= ngx.null then
    body.source_location = config.source_location
  end
  if config.tenant_id and config.tenant_id ~= ngx.null then
    body.tenant_id = config.tenant_id
  end
  if config.collector_instance_id and config.collector_instance_id ~= ngx.null then
    body.collector_instance_id = config.collector_instance_id
  end

  local service = kong.router.get_service()
  body.extra_info = {}
  if service and service.name then
    body.extra_info.app_name = service.name
  end
  if config.extra_info and config.extra_info ~= ngx.null then
    for k, v in pairs(config.extra_info) do
      body.extra_info[k] = v
    end
  end

  return body
end

local function run_ai_guard(config, mode, raw_original_body)
  local exit_fn = kong.response.exit

  local original_body, err = cjson.decode(raw_original_body)
  if err then
    kong.log.err("Error decoding input body: " .. err)
    return exit_fn(400, { status = "Failed to decode JSON body", reason = err })
  end

  local translator_instance, terr = get_translator(config.upstream_llm.provider)
  if terr ~= nil or translator_instance == nil then
    kong.log.err("Failed to get translator " .. terr)
    return exit_fn(500, internalError)
  end

  local api_uri    = config.upstream_llm.api_uri:gsub("^%s+", ""):gsub("%s+$", "")
  local transformer = translator_instance[api_uri]
  if transformer == nil then
    kong.log.debug(string.format(
      "Could not find transformer for provider '%s' for upstream uri '%s'",
      config.upstream_llm.provider, api_uri))
    return exit_fn(500, internalError)
  end

  local messages, merr = transformer[mode](original_body)
  if merr ~= nil then
    kong.log.err("Failed to process message: " .. merr)
    return exit_fn(500, internalError)
  end

  if #messages.messages == 0 then
    kong.log.debug("No messages found, skipping AIDR")
    return
  end

  local url = config.ai_guard_api_base_url .. "/v1/guard_chat_completions"
  local ai_guard_request_body = get_aidr_fields(config, mode)
  ai_guard_request_body.guard_input = { messages = messages.messages }
  if messages.tools and #messages.tools > 0 then
    ai_guard_request_body.guard_input.tools = messages.tools
  end

  local raw_ai_guard_request_body, eerr = cjson.encode(ai_guard_request_body)
  if eerr then
    kong.log.err("Error encoding request body: " .. eerr)
    return exit_fn(500, internalError)
  end

  local httpc      = http.new()
  local res, herr = httpc:request_uri(url, {
    method  = "POST",
    body    = raw_ai_guard_request_body,
    headers = {
      ["Authorization"] = "Bearer " .. config.ai_guard_api_key,
      ["Content-Type"]  = "application/json",
    },
  })

  if herr then
    kong.log.err("Error making request to CrowdStrike AIDR: " .. herr)
    return exit_fn(500, internalError)
  end

  if res.status ~= 200 then
    kong.log.err("CrowdStrike AIDR returned error: ", res.status, " ", res.body)
    return exit_fn(500, internalError)
  end

  local response, derr = cjson.decode(res.body)
  if derr then
    kong.log.err("Error decoding CrowdStrike AIDR response: " .. derr)
    return exit_fn(500, internalError)
  end

  if type(response.result) ~= "table" then
    kong.log.err("CrowdStrike AIDR response missing or invalid result field")
    return exit_fn(500, internalError)
  end

  if response.result.blocked then
    return exit_fn(400, {
      status = "Prompt has been rejected by CrowdStrike AIDR",
      reason = response.summary or "Content blocked by AIDR policy",
    })
  end

  kong.log.debug("CrowdStrike AIDR: content allowed")

  local capabilities = translator_instance.capabilities or {}
  local can_redact   = capabilities.redaction
  if can_redact == nil then can_redact = true end

  if not can_redact then
    kong.log.debug("Skipping redaction step")
    return
  end

  if not response.result.transformed then return end

  local guard_output = response.result.guard_output
  if not guard_output or not guard_output.messages then
    kong.log.debug("No guard_output.messages in response, skipping redaction")
    return
  end

  local new_messages = guard_output.messages
  if #new_messages > 0 then
    local new_payload, updated = rewrite_llm_message(original_body, messages, new_messages)
    if updated then
      kong.log.debug("CrowdStrike AIDR: required redaction")
      local raw_new_payload, rencode_err = cjson.encode(new_payload)
      if rencode_err ~= nil then
        kong.log.err("Failed to encode redacted payload: " .. rencode_err)
        return exit_fn(500, internalError)
      end
      return raw_new_payload
    end
  end
end

HANDLER_EOF

  # Append the plugin-specific handler body
  append_plugin_handler "$plugin" "$priority" "$version" "$handler_class" >> "$dest/handler.lua"
}

append_plugin_handler() {
  local plugin="$1"
  local priority="$2"
  local version="$3"
  local handler_class="$4"

  case "$plugin" in
    crowdstrike-aidr-request)
      cat << PLUGIN_EOF

-- ---------------------------------------------------------------------------
-- plugin: crowdstrike-aidr-request
-- ---------------------------------------------------------------------------
local MAX_BUFFERED_BODY_SIZE = 1024 * 1024

local function get_raw_body()
  local raw_body, err = kong.request.get_raw_body(MAX_BUFFERED_BODY_SIZE)
  if raw_body == nil then return nil, err end
  local encoding = kong.request.get_header("Content-Encoding")
  if encoding == "gzip" then
    raw_body = gzip.inflate_gzip(raw_body)
  end
  return raw_body
end

local Handler = { PRIORITY = $priority, VERSION = "$version" }

function Handler:access(config)
  local method = kong.request.get_method()
  if method ~= "POST" and method ~= "PUT" and method ~= "PATCH" then return end

  local raw_body, err = get_raw_body()
  if raw_body == nil then
    kong.log.err("Failed to read request body, skipping AIDR: ", err)
    return
  end
  if raw_body == "" then
    kong.log.debug("No body found, skipping AIDR")
    return
  end

  local new_payload = run_ai_guard(config, "request", raw_body)
  if new_payload ~= nil then
    kong.service.request.set_raw_body(new_payload)
  end
end

return Handler
