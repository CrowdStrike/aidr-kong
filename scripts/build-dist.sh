local Bedrock = (function()
  local function convert_tools(bedrock_tools)
    local tools = {}
    for _, tool in ipairs(bedrock_tools) do
      local spec = type(tool) == "table" and tool.toolSpec
      if spec and type(spec.name) == "string" then
        local parameters = spec.inputSchema and spec.inputSchema.json
        table.insert(tools, {
          type = "function",
          ["function"] = {
            name        = spec.name,
            description = spec.description,
            parameters  = parameters,
          },
        })
      end
    end
    return tools
  end

  local function prepare_converse_request(request)
    if type(request) ~= "table" then return nil, "Invalid llm request" end
    local ret = NewJSONMessageMap()
    for idx, system_content in ipairs(request.system) do
      local text = system_content.text
      if text ~= nil then
        ret:add_message(text, "system", { "system", idx, "text" })
      end
    end
    for idx, message in ipairs(request.messages) do
      local role = message.role
      for jdx, content in ipairs(message.content) do
        local text = content.text
        if text ~= nil then
          ret:add_message(text, role, { "messages", idx, "content", jdx, "text" })
        elseif type(content.toolResult) == "table" then
          local tool_result = content.toolResult
          if type(tool_result.content) == "table" then
            for kdx, block in ipairs(tool_result.content) do
              if type(block.text) == "string" then
                ret:add_message(block.text, role,
                  { "messages", idx, "content", jdx, "toolResult", "content", kdx, "text" })
              end
            end
          end
        end
      end
    end
    local tool_config = request.toolConfig
    if type(tool_config) == "table" and type(tool_config.tools) == "table" and #tool_config.tools > 0 then
      ret.tools = convert_tools(tool_config.tools)
    end
    return ret
  end

  local function prepare_converse_response(response)
    if type(response) ~= "table" then return nil, "Invalid response object" end
    if type(response.output) ~= "table" or type(response.output.message) ~= "table" then
      return nil, "Invalid response object"
    end
    local ret     = NewJSONMessageMap()
    local message = response.output.message
    local role    = message.role or "assistant"
    for jdx, content in ipairs(message.content) do
      local text = content.text
      if text ~= nil then
        ret:add_message(text, role, { "output", "message", "content", jdx, "text" })
      end
    end
    return ret
  end

  return {
    ["converse"] = {
      request  = prepare_converse_request,
      response = prepare_converse_response,
    },
    capabilities = { redaction = false },
  }
end)()

-- ---------------------------------------------------------------------------
-- translator: cohere (reuses OpenAI request handler)
-- ---------------------------------------------------------------------------
local Cohere = (function()
  local function prepare_messages_from_llm_response(response)
    if type(response) ~= "table" then return nil, "Invalid response object" end
    local messages = response.message
    if messages == nil or type(messages) ~= "table" then return nil, "Invalid response object" end
    local ret  = NewJSONMessageMap()
    local role = messages.role
    for idx, content in ipairs(messages.content) do
      if content.type == "text" then
        ret:add_message(content.text, role, { "message", "content", idx, "text" })
      end
    end
    return ret
  end

  return {
    ["/v2/chat"] = {
      request  = OpenAI["/v1/chat/completions"].request,
      response = prepare_messages_from_llm_response,
    },
  }
end)()

-- ---------------------------------------------------------------------------
-- translator: gemini
-- ---------------------------------------------------------------------------
local Gemini = (function()
  local function convert_tools(gemini_tools)
    local tools = {}
    for _, tool_group in ipairs(gemini_tools) do
      local decls = type(tool_group) == "table" and tool_group.functionDeclarations
      if type(decls) == "table" then
        for _, decl in ipairs(decls) do
          if type(decl) == "table" and type(decl.name) == "string" then
            table.insert(tools, {
              type = "function",
              ["function"] = {
                name        = decl.name,
                description = decl.description,
                parameters  = decl.parameters,
              },
            })
          end
        end
      end
    end
    return tools
  end

  local function transform_role(role)
    if role == "model" then return AidrRoles.PromptRoleLlm end
    return role
  end

  local function prepare_chat_completions_request(request)
    if type(request) ~= "table" then return nil, "Invalid llm request" end
    local ret    = NewJSONMessageMap()
    local system = request.system_instructions
    if system ~= nil then
      for idx, part in ipairs(system.parts) do
        if part.text ~= nil then
          ret:add_message(part.text, "system", { "system_instructions", "parts", idx, "text" })
        end
      end
    end
    for idx, content in ipairs(request.contents) do
      local role = transform_role(content.role)
      for jdx, part in ipairs(content.parts) do
        if part.text ~= nil then
          ret:add_message(part.text, role, { "contents", idx, "parts", jdx, "text" })
        end
      end
    end
    if type(request.tools) == "table" and #request.tools > 0 then
      local tools = convert_tools(request.tools)
      if #tools > 0 then ret.tools = tools end
    end
    return ret
  end

  local function prepare_chat_completions_response(response)
    if type(response) ~= "table" then return nil, "Invalid llm request" end
    local ret = NewJSONMessageMap()
    for idx, candidate in ipairs(response.candidates) do
      for jdx, content in ipairs(candidate.content) do
        local role = transform_role(content.role) or AidrRoles.PromptRoleLlm
        for kdx, part in ipairs(content.parts) do
          if part.text ~= nil then
            ret:add_message(part.text, role, { "candidates", idx, "content", jdx, "parts", kdx, "text" })
          end
        end
      end
    end
    return ret
  end

  return {
    ["/v1/models"]    = { request = prepare_chat_completions_request, response = prepare_chat_completions_response },
    ["generateContent"] = { request = prepare_chat_completions_request, response = prepare_chat_completions_response },
  }
end)()

